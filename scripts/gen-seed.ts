/**
 * Generates sql/seed.sql from the current local SQLite database
 * (db/custom.db — created by the previous Prisma setup).
 *
 * The output is used to seed BOTH the local dev database
 * (scripts/setup-local.ts) and the production Cloudflare D1 database
 * (first deploy only, detected via the _meta table).
 *
 * Usage: bun scripts/gen-seed.ts
 */
import { Database } from "bun:sqlite";

const SOURCE = "db/custom.db";
const TARGET = "sql/seed.sql";

/** Old Prisma table name → new table name. Column names are unchanged. */
const TABLES: Array<[string, string]> = [
  ["SiteSetting", "site_setting"],
  ["Skill", "skill"],
  ["Project", "project"],
  ["Experience", "experience"],
  ["Education", "education"],
  ["Service", "service"],
  ["Testimonial", "testimonial"],
  ["SocialLink", "social_link"],
  ["Stat", "stat"],
];

const DATE_COLUMNS = new Set(["createdAt", "updatedAt"]);

function sqlStr(value: unknown): string {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number" || typeof value === "bigint") return String(value);
  const s = String(value);
  return `'${s.replace(/'/g, "''")}'`;
}

function convertValue(col: string, value: unknown): string {
  // Prisma stored DateTime either as epoch-ms numbers or as
  // "YYYY-MM-DD HH:mm:ss" (UTC) strings — normalize both to ISO.
  if (DATE_COLUMNS.has(col)) {
    if (typeof value === "number") return sqlStr(new Date(value).toISOString());
    if (typeof value === "string" && /^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}$/.test(value)) {
      return sqlStr(`${value.replace(" ", "T")}.000Z`);
    }
  }
  return sqlStr(value);
}

async function pbkdf2Hash(password: string, saltHex: string, iterations = 100_000): Promise<string> {
  const enc = new TextEncoder();
  const salt = new Uint8Array(Math.floor(saltHex.length / 2));
  for (let i = 0; i < salt.length; i++) salt[i] = parseInt(saltHex.slice(i * 2, i * 2 + 2), 16);
  const key = await crypto.subtle.importKey("raw", enc.encode(password), "PBKDF2", false, ["deriveBits"]);
  const bits = await crypto.subtle.deriveBits(
    { name: "PBKDF2", hash: "SHA-256", salt: salt as unknown as BufferSource, iterations },
    key,
    256
  );
  const hex = Array.from(new Uint8Array(bits), (b) => b.toString(16).padStart(2, "0")).join("");
  return `pbkdf2:${iterations}:${saltHex}:${hex}`;
}

const db = new Database(SOURCE, { readonly: true });
const lines: string[] = [
  "-- ============================================================",
  "-- Portfolio seed data (generated by scripts/gen-seed.ts).",
  "-- Applied ONCE on first deploy; all statements are idempotent",
  "-- (INSERT OR IGNORE) so accidental re-runs stay safe.",
  "-- ============================================================",
  "",
];

for (const [oldName, newName] of TABLES) {
  const rows = db.query(`SELECT * FROM "${oldName}"`).all() as Record<string, unknown>[];
  lines.push(`-- ${newName} (${rows.length} rows)`);
  for (const row of rows) {
    const cols = Object.keys(row);
    const vals = cols.map((c) => convertValue(c, row[c]));
    lines.push(
      `INSERT OR IGNORE INTO "${newName}" (${cols.map((c) => `"${c}"`).join(", ")}) VALUES (${vals.join(", ")});`
    );
  }
  lines.push("");
}

// Fresh admin account (password: admin123 — change it from the admin
// panel after the first login!). PBKDF2 hash is deterministic so this
// seed can be regenerated at any time.
const hash = await pbkdf2Hash("admin123", "6d796f6e6c796f6e6568657265");
const now = new Date().toISOString();
lines.push(`-- admin (default password: admin123 — CHANGE IT after first login)`);
lines.push(
  `INSERT OR IGNORE INTO "admin" ("id","username","passwordHash","createdAt","updatedAt") VALUES ('admin-main','admin',${sqlStr(hash)},${sqlStr(now)},${sqlStr(now)});`
);
lines.push("");
lines.push(`-- mark the database as seeded (checked by the deploy workflow)`);
lines.push(`INSERT OR IGNORE INTO "_meta" ("key","value") VALUES ('seeded','1');`);
lines.push("");

await Bun.write(TARGET, lines.join("\n"));
console.log(`✓ wrote ${TARGET} (${lines.length} lines)`);
